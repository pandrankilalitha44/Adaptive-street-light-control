/*
    File: types.h
    -------------------------------------------------------
    This header file defines user-created data type aliases
    used throughout the embedded C project.
    These aliases make variable declarations shorter and
    easier to understand.
*/

// Alias for an unsigned 32-bit integer type.
typedef unsigned int u32;
// Alias for an unsigned 8-bit integer type.
typedef unsigned char u8;
// Alias for a signed 32-bit integer type.
typedef signed int s32;
// Alias for a signed 8-bit integer type.
typedef signed char s8;
// Alias for a floating-point data type.
typedef float f32;
// Alias for an unsigned integer type (as defined in the original file).
typedef unsigned int u16;

